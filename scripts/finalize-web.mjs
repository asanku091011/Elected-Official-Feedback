// Runs after `expo export --platform web`.
//
// Expo's web export writes a single index.html and the JavaScript bundle. This
// script adds the pieces a browser needs to install CivLink like an app:
//   - a web app manifest with 192px and 512px icons
//   - an Apple touch icon and the iOS standalone meta tags
//   - a small service worker, registered only on https (or localhost)
//
// It is plain Node, with no extra dependencies, and it fails loudly if the
// export is missing so a broken deploy cannot look successful.

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DIST = path.join(ROOT, 'dist');
const INDEX = path.join(DIST, 'index.html');
const ICON_DIR = path.join(DIST, 'icons');

const ICONS = [
  ['assets/branding/icon-192.png', 'icon-192.png'],
  ['assets/branding/icon-512.png', 'icon-512.png'],
  ['assets/branding/apple-touch-icon.png', 'apple-touch-icon.png'],
];

const THEME = '#38CBD0';
const START_MARKER = '<!-- civlink-pwa -->';

const MANIFEST = {
  id: '/',
  name: 'CivLink — find the office that can act',
  short_name: 'CivLink',
  description:
    'Find the office of government that can act on a concern, write a clear message, and follow updates from your Northern Virginia area.',
  start_url: '/',
  scope: '/',
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#FFFFFF',
  theme_color: THEME,
  lang: 'en-US',
  categories: ['government', 'education', 'productivity'],
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};

const HEAD_TAGS = `
    ${START_MARKER}
    <meta name="theme-color" content="${THEME}" />
    <meta name="description" content="${MANIFEST.description}" />
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="apple-touch-icon" sizes="180x180" href="/icons/apple-touch-icon.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="apple-mobile-web-app-title" content="CivLink" />`;

// The service worker keeps a copy of the shell so a flaky connection shows the
// app instead of the browser's offline page. New deploys replace the old cache.
const SERVICE_WORKER = `// Generated by scripts/finalize-web.mjs
const CACHE = 'civlink-shell-v1';
const SHELL = ['./', './index.html', './icons/icon-192.png', './icons/icon-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  // Navigations go to the network first so a fresh deploy is picked up, then
  // fall back to the cached shell when the device is offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request)
        .then((response) => {
          if (response.ok && new URL(request.url).origin === self.location.origin) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match('./index.html'));
    })
  );
});
`;

const REGISTER = `
    <script>
      if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost')) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('/sw.js').catch(function () {
            /* The app works without the offline shell; nothing to report to the resident. */
          });
        });
      }
    </script>`;

async function main() {
  if (!existsSync(INDEX)) {
    throw new Error('dist/index.html is missing. Run `npx expo export --platform web` first.');
  }

  await mkdir(ICON_DIR, { recursive: true });
  for (const [from, name] of ICONS) {
    if (!existsSync(path.join(ROOT, from))) {
      throw new Error(`Missing icon asset: ${from}`);
    }
    await copyFile(path.join(ROOT, from), path.join(ICON_DIR, name));
  }

  await writeFile(path.join(DIST, 'manifest.webmanifest'), `${JSON.stringify(MANIFEST, null, 2)}\n`);
  await writeFile(path.join(DIST, 'sw.js'), SERVICE_WORKER);

  let html = await readFile(INDEX, 'utf8');
  // Running the export twice should not stack duplicate tags.
  html = html.replace(/\n    <!-- civlink-pwa -->[\s\S]*?<meta name="apple-mobile-web-app-title" content="CivLink" \/>/, '');
  html = html.replace('</head>', `${HEAD_TAGS}\n  </head>`);
  html = html.replace('</body>', `${REGISTER}\n</body>`);
  await writeFile(INDEX, html);

  console.log('PWA ready: manifest.webmanifest, sw.js, icons, and install meta tags added to dist.');
}

main().catch((error) => {
  console.error(`finalize-web failed: ${error.message}`);
  process.exit(1);
});
